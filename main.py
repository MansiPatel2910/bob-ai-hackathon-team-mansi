class C:
    """ANSI color/style kernel. No external deps -> zero install risk on demo day."""
    RESET   = "\033[0m"
    BOLD    = "\033[1m"
    DIM     = "\033[2m"
    ITALIC  = "\033[3m"
    UNDER   = "\033[4m"

    FG_CYAN    = "\033[38;5;51m"
    FG_TEAL    = "\033[38;5;44m"
    FG_BLUE    = "\033[38;5;39m"
    FG_INDIGO  = "\033[38;5;99m"
    FG_GREEN   = "\033[38;5;46m"
    FG_AMBER   = "\033[38;5;214m"
    FG_RED     = "\033[38;5;196m"
    FG_MAGENTA = "\033[38;5;201m"
    FG_GREY    = "\033[38;5;245m"
    FG_WHITE   = "\033[38;5;255m"

    BG_DARK    = "\033[48;5;235m"

    @staticmethod
    def wrap(text: str, *codes: str) -> str:
        return f"{''.join(codes)}{text}{C.RESET}"


def term_width(default: int = 96) -> int:
    try:
        w = shutil.get_terminal_size(fallback=(default, 24)).columns
        return max(80, min(w, 120))
    except Exception:
        return default


def hr(char: str = "─", color: str = C.FG_GREY) -> str:
    return C.wrap(char * term_width(), color)


def panel(title: str, lines: list[str], color: str = C.FG_CYAN, icon: str = "◆") -> str:
    """Render a box-drawn panel with a titled header — the visual signature of the CLI."""
    w = term_width()
    inner = w - 2
    top = f"{color}╭{'─' * inner}╮{C.RESET}"
    title_line = f" {icon} {C.BOLD}{title}{C.RESET}{color}"
    pad = inner - len(f" {icon} {title}") 
    title_row = f"{color}│{C.RESET}{title_line}{' ' * max(pad, 0)}{color}│{C.RESET}"
    sep = f"{color}├{'─' * inner}┤{C.RESET}"
    body = []
    for ln in lines:
        for wrapped in (textwrap.wrap(ln, inner - 2) or [""]):
            pad2 = inner - 2 - len(_strip_ansi(wrapped))
            body.append(f"{color}│{C.RESET} {wrapped}{' ' * max(pad2, 0)} {color}│{C.RESET}")
    bottom = f"{color}╰{'─' * inner}╯{C.RESET}"
    return "\n".join([top, title_row, sep, *body, bottom])


def _strip_ansi(s: str) -> str:
    import re
    return re.sub(r"\033\[[0-9;]*m", "", s)


def table(headers: list[str], rows: list[list[str]], widths: list[int] | None = None,
          accent: str = C.FG_TEAL) -> str:
    if widths is None:
        widths = []
        for i, h in enumerate(headers):
            col = [h] + [str(r[i]) for r in rows]
            widths.append(max(len(_strip_ansi(c)) for c in col) + 2)

    def fmt_row(cells: list[str]) -> str:
        out = []
        for c_, w in zip(cells, widths):
            pad = w - len(_strip_ansi(c_))
            out.append(c_ + " " * max(pad, 0))
        return "│ " + " │ ".join(out) + " │"

    top = "╭" + "┬".join("─" * (w + 2) for w in widths) + "╮"
    sep = "├" + "┼".join("─" * (w + 2) for w in widths) + "┤"
    bot = "╰" + "┴".join("─" * (w + 2) for w in widths) + "╯"
    head_cells = [C.wrap(h, C.BOLD, accent) for h in headers]
    lines = [C.wrap(top, accent), fmt_row(head_cells), C.wrap(sep, accent)]
    for r in rows:
        lines.append(fmt_row([str(c) for c in r]))
    lines.append(C.wrap(bot, accent))
    return "\n".join(lines)


def spinner_burst(msg: str, ticks: int = 10, delay: float = 0.02) -> None:
    frames = "⠋⠙⠹⠸⠼⠴⠦⠧⠇⠏"
    for i in range(ticks):
        sys.stdout.write(f"\r{C.wrap(frames[i % len(frames)], C.FG_CYAN)} {C.DIM}{msg}{C.RESET}")
        sys.stdout.flush()
        time.sleep(delay)
    sys.stdout.write("\r" + " " * (len(msg) + 4) + "\r")


def typewriter(text: str, delay: float = 0.006, color: str = C.FG_WHITE) -> None:
    for ch in text:
        sys.stdout.write(C.wrap(ch, color))
        sys.stdout.flush()
        time.sleep(delay)
    print()


