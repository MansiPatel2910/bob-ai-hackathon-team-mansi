@dataclass
class MaterialRisk:
    material: str
    use_case: str
    china_share_pct: float
    hhi_score: int              # Herfindahl-Hirschman Index (supply concentration)
    export_control_active: bool
    alt_source_lead_weeks: int
    risk_tier: str = ""
    risk_score: int = 0


class GeopoliticalMatrix:
    """
    Scores single-source / concentrated-source material dependencies
    against active export-control posture. Modeled on real 2023-2025
    critical-mineral exposure for advanced-node semiconductor supply
    chains (gallium & germanium export licensing; neon gas concentration
    from Eastern-European electrolytic byproduct streams).
    """

    MATERIALS = [
        ("Gallium", "III-V epitaxy, RF power amps, GaN substrates", 82.0, 6900, True, 24),
        ("Germanium", "IR optics, SiGe transistors, fiber-optic substrates", 68.0, 5400, True, 20),
        ("Neon (electronic grade)", "Excimer laser gas mix for DUV lithography scanners", 35.0, 3100, False, 14),
        ("Palladium", "Interconnect plating, wire-bond alternatives", 41.0, 2800, False, 10),
        ("Tungsten", "Contact plugs, interconnect barrier layers", 58.0, 4200, False, 16),
    ]

    def assess(self) -> list[MaterialRisk]:
        results = []
        for name, use, share, hhi, ctrl, lead in self.MATERIALS:
            score = 0
            score += min(share, 100) * 0.5
            score += (hhi / 10000) * 100 * 0.3
            score += (20 if ctrl else 0)
            score += min(lead, 30) * 0.5
            score = round(score)
            tier = "SEVERE" if score >= 70 else "ELEVATED" if score >= 50 else "MODERATE"
            results.append(MaterialRisk(name, use, share, hhi, ctrl, lead, tier, score))
        results.sort(key=lambda m: -m.risk_score)
        return results

    def render(self, risks: list[MaterialRisk]) -> str:
        rows = []
        for r in risks:
            tcolor = {"SEVERE": C.FG_RED, "ELEVATED": C.FG_AMBER, "MODERATE": C.FG_BLUE}[r.risk_tier]
            ctrl_flag = C.wrap("● ACTIVE", C.BOLD, C.FG_RED) if r.export_control_active else C.wrap("○ none", C.FG_GREY)
            rows.append([
                C.wrap(r.material, C.BOLD),
                f"{r.china_share_pct:.0f}%",
                str(r.hhi_score),
                ctrl_flag,
                f"{r.alt_source_lead_weeks}wk",
                C.wrap(f"{r.risk_score}/100 {r.risk_tier}", C.BOLD, tcolor),
            ])
        return table(["MATERIAL", "CN SHARE", "HHI", "EXPORT CTRL", "ALT LEAD", "RISK SCORE"], rows)


