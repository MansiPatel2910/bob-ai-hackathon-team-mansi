@dataclass
class BottleneckAlert:
    tool_id: str
    tool_type: str
    model: str
    x_factor: float
    severity: str
    root_cause: str
    downstream_delay_days: float
    eta_shift_weeks: float
    confidence_pct: float


class BottleneckEngine:
    """
    Applies fab-standard operational thresholds to the live telemetry
    snapshot and projects the delay forward through downstream assembly,
    test, and shipment — up to a 52-week finished-goods horizon.

    Threshold model (industry-referenced heuristics):
        X-factor < 2.0        -> nominal
        2.0 <= X-factor < 3.0 -> WATCH   (early bottleneck signature)
        3.0 <= X-factor < 4.5 -> WARNING (active constraint, expedite)
        X-factor >= 4.5       -> CRITICAL (line-down risk, escalate to Bob)
    """

    X_WATCH = 2.0
    X_WARN = 3.0
    X_CRIT = 4.5

    # Days of downstream buffer consumed per excess X-factor point,
    # calibrated against typical 60-90 day fab-to-finished-goods cycle.
    DELAY_COEFFICIENT_DAYS = 6.5

    ROOT_CAUSES = {
        "LITHO": "EUV pellicle degradation + reticle qualification backlog",
        "ETCH": "Plasma chamber matching drift across parallel Kiyo/Centura modules",
        "CVD": "Precursor gas-line contamination flagged during in-situ QC",
    }

    def __init__(self, telemetry: TelemetrySimulator):
        self.telemetry = telemetry

    def scan(self) -> list[BottleneckAlert]:
        alerts = []
        for tool in self.telemetry.tools:
            xf = tool.x_factor
            if xf < self.X_WATCH and tool.state != ToolState.DOWN:
                continue

            if tool.state == ToolState.DOWN or xf >= self.X_CRIT:
                severity = "CRITICAL"
                conf = 96.0
            elif xf >= self.X_WARN:
                severity = "WARNING"
                conf = 90.0
            else:
                severity = "WATCH"
                conf = 78.0

            excess = max(xf - 1.0, 0.2)
            downstream_delay_days = round(excess * self.DELAY_COEFFICIENT_DAYS, 1)
            eta_shift_weeks = round(min(downstream_delay_days / 7.0 * self._fanout(tool), 52.0), 1)

            alerts.append(BottleneckAlert(
                tool_id=tool.tool_id,
                tool_type=tool.tool_type,
                model=tool.model,
                x_factor=xf,
                severity=severity,
                root_cause=self.ROOT_CAUSES.get(tool.tool_type, "Unclassified excursion"),
                downstream_delay_days=downstream_delay_days,
                eta_shift_weeks=eta_shift_weeks,
                confidence_pct=conf,
            ))
        alerts.sort(key=lambda a: {"CRITICAL": 0, "WARNING": 1, "WATCH": 2}[a.severity])
        return alerts

    @staticmethod
    def _fanout(tool: ToolNode) -> float:
        """Downstream fan-out multiplier: a delay at a shared/bottleneck
        module (high WIP count) propagates across more downstream lots."""
        return round(1.0 + (tool.wip_lots / 20.0), 2)

    def render(self, alerts: list[BottleneckAlert]) -> str:
        if not alerts:
            return panel("PREDICTIVE BOTTLENECK ENGINE", ["✔ All modules nominal — no X-factor breaches detected."], C.FG_GREEN, "✔")

        rows = []
        for a in alerts:
            scolor = {"CRITICAL": C.FG_RED, "WARNING": C.FG_AMBER, "WATCH": C.FG_BLUE}[a.severity]
            rows.append([
                C.wrap(a.tool_id, C.BOLD),
                a.tool_type,
                C.wrap(a.severity, C.BOLD, scolor),
                f"{a.x_factor}x",
                f"{a.downstream_delay_days}d",
                C.wrap(f"+{a.eta_shift_weeks} wk", C.BOLD, scolor),
                f"{a.confidence_pct}%",
            ])
        body = table(["TOOL", "MODULE", "SEVERITY", "X-FACTOR", "DELAY", "ETA SHIFT", "CONF."], rows)
        crit = [a for a in alerts if a.severity == "CRITICAL"]
        footer = ""
        if crit:
            worst = max(crit, key=lambda a: a.eta_shift_weeks)
            footer = (f"\n{C.wrap('⚠ HIGHEST-IMPACT PATH:', C.BOLD, C.FG_RED)} {worst.tool_id} "
                      f"({worst.model}) — {worst.root_cause}. "
                      f"Projected finished-goods ETA slip: "
                      f"{C.wrap(f'{worst.eta_shift_weeks} weeks', C.BOLD, C.FG_RED)} "
                      f"(of 52-week horizon), confidence {worst.confidence_pct}%.")
        return body + footer


