class ToolState(Enum):
    RUN = "RUN"
    IDLE = "IDLE"
    PM = "PM"        # preventive maintenance
    DOWN = "DOWN"     # unplanned excursion


@dataclass
class ToolNode:
    """A single fab tool (workstation) in the process flow."""
    tool_id: str
    tool_type: str          # LITHO / ETCH / CVD
    model: str
    theoretical_cycle_min: float   # raw process time per lot (min)
    bay: str
    state: ToolState = ToolState.RUN
    oee_pct: float = 0.0
    q_time_min: float = 0.0
    wip_lots: int = 0
    mtbf_hr: float = 0.0
    mttr_hr: float = 0.0

    @property
    def x_factor(self) -> float:
        """X-factor = actual cycle time / theoretical (raw) process time.
        The single most-watched cadence metric on a fab floor."""
        actual = self.theoretical_cycle_min + self.q_time_min
        return round(actual / self.theoretical_cycle_min, 2)


@dataclass
class WipLot:
    lot_id: str
    product: str
    wafers: int
    priority: str
    current_step: str
    tool_id: str
    q_time_min: float


class TelemetrySimulator:
    """
    Generates a physically-plausible live snapshot of fab WIP across the
    three critical modules named in the S2 problem statement: Lithography
    (EUV/DUV scanners), Plasma Etch, and CVD deposition.
    """

    TOOLSETS = [
        ("LITHO", "ASML TWINSCAN NXE:3600D (EUV)", "Bay-3 EUV Pod", 46.0),
        ("LITHO", "ASML TWINSCAN NXT:2000i (DUV)", "Bay-3 DUV Pod", 31.5),
        ("ETCH",  "Lam Research Kiyo® FX Conductor", "Bay-5 Etch Pod", 18.2),
        ("ETCH",  "Applied Materials Centura® AP",   "Bay-5 Etch Pod", 21.7),
        ("CVD",   "Applied Materials Producer® GT",   "Bay-6 Dep Pod", 27.4),
        ("CVD",   "ASM A412™ Advance Dielectric",     "Bay-6 Dep Pod", 24.9),
    ]

    PRODUCTS = ["N3E-SoC-RevC", "HBM4-Logic-Die", "RF-FEM-22nm", "N5P-AI-Accel"]
    PRIORITIES = ["HOT-LOT", "STD", "STD", "ENG-SPLIT"]

    def __init__(self, seed: int = 2026):
        self.rng = random.Random(seed)
        self.tools: list[ToolNode] = self._spawn_tools()
        self.lots: list[WipLot] = self._spawn_lots()

    def _spawn_tools(self) -> list[ToolNode]:
        tools = []
        for idx, (ttype, model, bay, cyc) in enumerate(self.TOOLSETS):
            state_roll = self.rng.random()
            state = ToolState.RUN
            if state_roll > 0.92:
                state = ToolState.DOWN
            elif state_roll > 0.80:
                state = ToolState.PM

            # Etch is deliberately modeled as the constrained module for the
            # demo narrative: elevated queue times relative to raw process time.
            base_q = {
                "LITHO": self.rng.uniform(15, 55),
                "ETCH": self.rng.uniform(55, 145),
                "CVD": self.rng.uniform(10, 40),
            }[ttype]

            if state == ToolState.DOWN:
                base_q *= self.rng.uniform(2.2, 3.4)
            elif state == ToolState.PM:
                base_q *= self.rng.uniform(1.3, 1.8)

            tools.append(ToolNode(
                tool_id=f"{ttype[:2]}-{idx+1:02d}",
                tool_type=ttype,
                model=model,
                theoretical_cycle_min=cyc,
                bay=bay,
                state=state,
                oee_pct=round(self.rng.uniform(58, 91) if state == ToolState.RUN
                              else self.rng.uniform(0, 40), 1),
                q_time_min=round(base_q, 1),
                wip_lots=self.rng.randint(4, 28),
                mtbf_hr=round(self.rng.uniform(180, 640), 1),
                mttr_hr=round(self.rng.uniform(1.5, 9.5), 1),
            ))
        return tools

    def _spawn_lots(self) -> list[WipLot]:
        lots = []
        for i in range(9):
            tool = self.rng.choice(self.tools)
            lots.append(WipLot(
                lot_id=f"LOT-{2600 + i}",
                product=self.rng.choice(self.PRODUCTS),
                wafers=25,
                priority=self.rng.choice(self.PRIORITIES),
                current_step=f"{tool.tool_type}-STEP-{self.rng.randint(1,9)}",
                tool_id=tool.tool_id,
                q_time_min=round(self.rng.uniform(5, 180), 1),
            ))
        return lots

    def render_dashboard(self) -> str:
        rows = []
        for t in self.tools:
            state_color = {
                ToolState.RUN: C.FG_GREEN,
                ToolState.IDLE: C.FG_GREY,
                ToolState.PM: C.FG_AMBER,
                ToolState.DOWN: C.FG_RED,
            }[t.state]
            xf_color = C.FG_RED if t.x_factor >= 3.0 else (C.FG_AMBER if t.x_factor >= 2.0 else C.FG_GREEN)
            rows.append([
                C.wrap(t.tool_id, C.BOLD),
                t.model,
                C.wrap(t.state.value, C.BOLD, state_color),
                f"{t.oee_pct}%",
                f"{t.q_time_min}m",
                C.wrap(f"{t.x_factor}x", C.BOLD, xf_color),
                str(t.wip_lots),
            ])
        return table(
            ["TOOL", "MODEL", "STATE", "OEE", "Q-TIME", "X-FACTOR", "WIP"],
            rows,
        )

    def render_lot_stream(self) -> str:
        rows = []
        for lot in self.lots:
            pcolor = C.FG_RED if lot.priority == "HOT-LOT" else C.FG_GREY
            rows.append([
                C.wrap(lot.lot_id, C.FG_CYAN),
                lot.product,
                C.wrap(lot.priority, C.BOLD, pcolor),
                lot.current_step,
                lot.tool_id,
                f"{lot.q_time_min}m",
            ])
        return table(["LOT ID", "PRODUCT", "PRIORITY", "STEP", "TOOL", "Q-TIME"], rows)


