def interactive_loop(bob: BobAgent) -> None:
    print()
    print(panel(
        "INTERACTIVE MODE",
        ["Ask Bob about WIP status, bottlenecks/ETA risk, or geopolitical material exposure.",
         "Type 'summary' for the exec brief, or 'exit' to end the session."],
        C.FG_TEAL, "⌨",
    ))
    while True:
        try:
            query = input(C.wrap("\n▶ Fab Ops Director › ", C.BOLD, C.FG_WHITE))
        except (EOFError, KeyboardInterrupt):
            print("\n" + C.wrap("Session terminated.", C.FG_GREY))
            break
        if not query.strip():
            continue
        if query.strip().lower() in {"exit", "quit", "q"}:
            print(C.wrap("◆ IBM Bob:", C.BOLD, C.FG_MAGENTA), "Session closed. Handing control back to the fab MES.")
            break
        spinner_burst("Bob is querying MCP tools + reasoning over telemetry", ticks=10, delay=0.015)
        print(C.wrap("◆ IBM Bob:", C.BOLD, C.FG_MAGENTA))
        print(bob.answer(query))


